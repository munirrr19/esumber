CREATE TABLE IF NOT EXISTS bookings (
  id INTEGER PRIMARY KEY, nama TEXT NOT NULL, tujuan TEXT NOT NULL, room TEXT NOT NULL,
  date TEXT NOT NULL, start TEXT NOT NULL, end TEXT NOT NULL, peserta TEXT NOT NULL,
  created TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, CHECK (start < end));
CREATE INDEX IF NOT EXISTS idx_room_date ON bookings (room, date);
CREATE TABLE IF NOT EXISTS teachers (id INTEGER PRIMARY KEY, nama TEXT NOT NULL UNIQUE);
CREATE INDEX IF NOT EXISTS idx_date ON bookings (date);
